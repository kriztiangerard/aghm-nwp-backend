-- NWP-PRICE-009
-- Pricing schema updates for the Price updater (NWP-PRICE-002 to 008).
--
-- Depends on: 001_initial_schema.sql (pricing.is_stale, consecutive_failure_count and
-- needs_manual_review already exist there; this migration only makes sure of them).
--
-- Pricing sources are distributor LISTING pages (decision 2026-11-19), so pricing_source keeps its
-- vendor + distributor shape. A device's synchronized price row records the listing page it came from
-- in pricing.source_id.
--
-- Changes:
--   1. pricing: one row per device and distributor (UNIQUE), checked first.
--   2. pricing.pricing_id and update_log.upd_log_id get IDENTITY defaults, so parallel sync batches
--      (NWP-PRICE-011) no longer compute ids with MAX + 1 and collide.
--   3. Failure-tracking columns confirmed, plus CHECK (consecutive_failure_count >= 0).
--   4. Indexes: pricing.source_id (failure attribution), update_log run_at and latest-status lookups.
--   5. Column comments.
--   6. Identity sequences of pricing, update_log, vendor, distributor, pricing_source and device are moved
--      FORWARD past their table's highest id, only when they are behind it (rows inserted with explicit ids
--      do not advance them). A sequence that is already ahead, or a sequence of an empty table, is left
--      exactly as it is, so a second run changes nothing.
--
-- Safe to run more than once. Runs in one transaction: if a guard stops it, nothing is applied.
-- Sequence changes (setval) are not undone by a rollback, so they run last: a failure in steps 1 to 5
-- leaves every sequence untouched. They only ever move forward, so even a later failure cannot cause an
-- id collision; at most some ids are skipped.
-- Run scripts/pricing-schema-precheck.sql first to see anything the guard would stop on;
-- run scripts/pricing-schema-check.sql afterwards to confirm. Rollback: db/migrations/rollback/.

BEGIN;

-- ============================================================
-- 1. Guard and UNIQUE: one pricing row per device and distributor
-- ============================================================

DO $$
DECLARE
    duplicate_pairs INT;
BEGIN
    SELECT count(*) INTO duplicate_pairs
    FROM (
        SELECT device_id, distributor_id
        FROM pricing
        GROUP BY device_id, distributor_id
        HAVING count(*) > 1
    ) AS d;

    IF duplicate_pairs > 0 THEN
        RAISE EXCEPTION 'NWP-PRICE-009: % device/distributor pair(s) have more than one pricing row. Resolve them first (scripts/pricing-schema-precheck.sql lists them). Nothing was changed.', duplicate_pairs;
    END IF;

    IF NOT EXISTS (
        SELECT 1 FROM pg_constraint
        WHERE conname = 'pricing_device_distributor_key'
          AND conrelid = 'public.pricing'::regclass
    ) THEN
        ALTER TABLE pricing
            ADD CONSTRAINT pricing_device_distributor_key UNIQUE (device_id, distributor_id);
    END IF;
END $$;

-- ============================================================
-- 2. IDENTITY defaults for pricing_id and upd_log_id
-- ============================================================

DO $$
BEGIN
    IF EXISTS (
        SELECT 1 FROM information_schema.columns
        WHERE table_schema = 'public' AND table_name = 'pricing'
          AND column_name = 'pricing_id' AND is_identity = 'NO'
    ) THEN
        ALTER TABLE pricing ALTER COLUMN pricing_id ADD GENERATED BY DEFAULT AS IDENTITY;
    END IF;

    IF EXISTS (
        SELECT 1 FROM information_schema.columns
        WHERE table_schema = 'public' AND table_name = 'update_log'
          AND column_name = 'upd_log_id' AND is_identity = 'NO'
    ) THEN
        ALTER TABLE update_log ALTER COLUMN upd_log_id ADD GENERATED BY DEFAULT AS IDENTITY;
    END IF;
END $$;

-- ============================================================
-- 3. Failure-tracking columns (already in 001; confirmed here)
-- ============================================================

ALTER TABLE pricing ADD COLUMN IF NOT EXISTS is_stale BOOLEAN NOT NULL DEFAULT FALSE;
ALTER TABLE pricing ADD COLUMN IF NOT EXISTS consecutive_failure_count INT NOT NULL DEFAULT 0;
ALTER TABLE pricing ADD COLUMN IF NOT EXISTS needs_manual_review BOOLEAN NOT NULL DEFAULT FALSE;

DO $$
BEGIN
    IF NOT EXISTS (
        SELECT 1 FROM pg_constraint
        WHERE conname = 'pricing_consecutive_failure_count_check'
          AND conrelid = 'public.pricing'::regclass
    ) THEN
        ALTER TABLE pricing
            ADD CONSTRAINT pricing_consecutive_failure_count_check CHECK (consecutive_failure_count >= 0);
    END IF;
END $$;

-- ============================================================
-- 4. Indexes
-- ============================================================

-- Devices last priced from a listing page (failure attribution, NWP-PRICE-004/005).
CREATE INDEX IF NOT EXISTS pricing_source_id_idx ON pricing (source_id);

-- Run result by run_at (NWP-PRICE-004) and latest status per device and distributor (NWP-PRICE-006).
CREATE INDEX IF NOT EXISTS update_log_run_at_idx ON update_log (run_at);
CREATE INDEX IF NOT EXISTS update_log_device_distributor_run_at_idx ON update_log (device_id, distributor_id, run_at DESC);

-- ============================================================
-- 5. Column documentation
-- ============================================================

COMMENT ON COLUMN pricing.source_id IS
    'Listing page (pricing_source) this synchronized price was last read from; NULL means the price was entered manually.';
COMMENT ON COLUMN pricing.is_stale IS
    'TRUE when the latest sync attempt for this synchronized row failed; the price is the last verified one. Never set on manual rows. NWP-PRICE-005.';
COMMENT ON COLUMN pricing.consecutive_failure_count IS
    'Consecutive failed sync attempts for this synchronized row; reset to 0 on success. NWP-PRICE-006.';
COMMENT ON COLUMN pricing.needs_manual_review IS
    'TRUE when every synchronized row of the device has failed 3+ consecutive runs (all distributors unavailable). NWP-PRICE-006.';
COMMENT ON COLUMN update_log.error IS
    'Details of any synchronization failure (retrieval, extraction, validation or database update).';
COMMENT ON COLUMN update_log.run_at IS
    'Start time of the synchronization run; shared by every row of the same run. NWP-PRICE-004.';

-- ============================================================
-- 6. Move identity sequences forward past existing ids (last: setval is not transactional)
-- ============================================================
-- Rows inserted with explicit ids (MAX + 1 in older scripts and migrations) do not advance an identity
-- sequence, so the next default id could collide with them. A sequence is moved only when the id it
-- would hand out next is not above the table's highest id; then setval(seq, max, true) makes the next
-- value max + 1. An empty table, or a sequence already ahead, is left alone (never moved backwards).

DO $$
DECLARE
    target RECORD;
    seq TEXT;
    max_id BIGINT;
    next_id BIGINT;
BEGIN
    FOR target IN
        SELECT * FROM (VALUES
            ('pricing', 'pricing_id'),
            ('update_log', 'upd_log_id'),
            ('vendor', 'vendor_id'),
            ('distributor', 'distributor_id'),
            ('pricing_source', 'source_id'),
            ('device', 'device_id')
        ) AS t(table_name, column_name)
    LOOP
        seq := pg_get_serial_sequence('public.' || target.table_name, target.column_name);
        CONTINUE WHEN seq IS NULL;   -- not an identity/serial column in this database
        EXECUTE format('SELECT max(%I) FROM public.%I', target.column_name, target.table_name) INTO max_id;
        CONTINUE WHEN max_id IS NULL;   -- empty table: nothing to collide with
        EXECUTE format('SELECT CASE WHEN is_called THEN last_value + 1 ELSE last_value END FROM %s', seq) INTO next_id;
        IF next_id <= max_id THEN
            PERFORM setval(seq, max_id, true);
        END IF;
    END LOOP;
END $$;

COMMIT;
